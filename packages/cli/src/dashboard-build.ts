import {
  cp,
  mkdir,
  readdir,
  readFile,
  rm,
  stat,
  writeFile,
} from 'node:fs/promises';
import { dirname, resolve, sep } from 'node:path';
import type { EvalRegistry } from '@evalkit/core';
import { createDashboardReportReader } from './dashboard-reports.js';

/** Marks a directory as EvalKit-owned so a rebuild may safely replace it. */
const MARKER = '.evalkit-dashboard';

export type DashboardBuildResult = {
  outDir: string;
  runs: number;
  trials: number;
  files: number;
};

/**
 * Write a read-only static dashboard: the bundled UI plus JSON snapshots of
 * the catalog and local reports, and each trial's candidate artifact files.
 * Evaluator workspaces are never copied; reports may still contain sensitive
 * messages, scores, or evidence, so review the output before sharing it.
 */
export async function buildDashboard(options: {
  registry: EvalRegistry;
  reportRoot: string;
  dashboardRoot: string;
  outDir: string;
}): Promise<DashboardBuildResult> {
  const { registry, reportRoot, dashboardRoot, outDir } = options;
  await prepareOutDir(outDir);
  await cp(dashboardRoot, outDir, { recursive: true });
  await writeFile(resolve(outDir, MARKER), 'Generated by `evalkit build`.\n');
  await writeFile(
    resolve(outDir, 'index.html'),
    staticIndex(await readFile(resolve(dashboardRoot, 'index.html'), 'utf8')),
  );

  const data = resolve(outDir, 'data');
  const write = async (path: string, value: unknown) => {
    const file = resolve(data, path);
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, `${JSON.stringify(value)}\n`);
  };
  const reports = createDashboardReportReader(reportRoot, registry);
  const runs = await reports.listRuns();
  await write('catalog.json', { evals: registry.catalog() });
  await write('evals.json', { evals: registry.metadata() });
  await write('suites.json', { suites: registry.suiteMetadata() });
  await write('runs.json', { runs });

  let trials = 0;
  let files = 0;
  for (const run of runs) {
    const runTrials = await reports.listTrials(run.id);
    await write(`runs/${run.id}/trials.json`, { trials: runTrials });
    for (const trial of runTrials) {
      trials += 1;
      const base = `runs/${run.id}/trials/${trial.id}`;
      await write(
        `${base}/detail.json`,
        await reports.trialDetail(run.id, trial.id),
      );
      await write(`${base}/events.json`, {
        events: await reports.trajectory(run.id, trial.id),
      });
      await write(`${base}/artifacts.json`, {
        artifacts: await reports.listArtifacts(run.id, trial.id),
      });
      const workspace = await reports.listCandidateWorkspace(run.id, trial.id);
      await write(`${base}/workspace.json`, workspace);
      for (const entry of workspace) {
        if (entry.kind !== 'file') continue;
        const response = await reports.candidateFile(
          run.id,
          trial.id,
          entry.path,
        );
        const target = resolve(data, base, 'workspace', entry.path);
        const root = resolve(data, base, 'workspace');
        if (!target.startsWith(`${root}${sep}`))
          throw new Error(`Invalid workspace path: ${entry.path}`);
        await mkdir(dirname(target), { recursive: true });
        await writeFile(target, new Uint8Array(await response.arrayBuffer()));
        files += 1;
      }
    }
  }
  return { outDir, runs: runs.length, trials, files };
}

/** Use relative asset URLs and select the static API in the browser bundle. */
export function staticIndex(html: string): string {
  const result = html
    .replace(
      '<html lang="en">',
      '<html lang="en" data-evalkit-snapshot="static">',
    )
    .replaceAll('"/assets/', '"./assets/');
  if (!result.includes('data-evalkit-snapshot="static"'))
    throw new Error('Bundled dashboard index.html has an unexpected shape');
  return result;
}

async function prepareOutDir(outDir: string): Promise<void> {
  let entries: string[];
  try {
    if (!(await stat(outDir)).isDirectory())
      throw new Error(`Output path is not a directory: ${outDir}`);
    entries = await readdir(outDir);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
    await mkdir(outDir, { recursive: true });
    return;
  }
  if (!entries.length) return;
  // Never delete a directory EvalKit did not create.
  if (!entries.includes(MARKER))
    throw new Error(
      `Refusing to overwrite ${outDir}: it is not empty and was not created by evalkit build`,
    );
  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });
}
