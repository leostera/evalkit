import {
  cp,
  mkdir,
  readdir,
  readFile,
  rm,
  stat,
  writeFile,
} from 'node:fs/promises';
import { dirname, resolve, sep } from 'node:path';
import { authoringId, type EvalRegistry } from '@evalkit/core';
import { dashboardIndex } from '@evalkit/share';
import { createDashboardReportReader } from './dashboard-reports.js';

/** Marks a directory as EvalKit-owned so a rebuild may safely replace it. */
const MARKER = '.evalkit-dashboard';

export type DashboardBuildResult = {
  outDir: string;
  runs: number;
  trials: number;
  files: number;
  /** Runs written by an older EvalKit, which this version cannot read. */
  skipped: number;
  /** Runs archived by `evalkit tidy`; never included in a snapshot. */
  archived: number;
};

/**
 * Write a read-only static dashboard: the bundled UI plus JSON snapshots of
 * the catalog and local reports, and each trial's candidate artifact files.
 * Evaluator workspaces are never copied; reports may still contain sensitive
 * messages, scores, or evidence, so review the output before sharing it.
 */
/** Runs one named phase of the build; the CLI uses it to time and display progress. */
export type BuildStep = <T>(
  label: string,
  work: (progress: (detail: string) => void) => Promise<T>,
  describe: (value: T) => string,
) => Promise<T>;

const quietStep: BuildStep = (_label, work) => work(() => {});

export async function buildDashboard(
  options: {
    registry: EvalRegistry;
    reportRoot: string;
    dashboardRoot: string;
    outDir: string;
  },
  step: BuildStep = quietStep,
): Promise<DashboardBuildResult> {
  const { registry, reportRoot, dashboardRoot, outDir } = options;
  const template = await readFile(resolve(dashboardRoot, 'index.html'), 'utf8');
  const data = resolve(outDir, 'data');
  const write = async (path: string, value: unknown) => {
    const file = resolve(data, path);
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, `${JSON.stringify(value)}\n`);
  };

  await step(
    'Dashboard assets',
    async () => {
      await prepareOutDir(outDir);
      await cp(dashboardRoot, outDir, { recursive: true });
      await writeFile(
        resolve(outDir, MARKER),
        'Generated by `evalkit build`.\n',
      );
      await writeFile(
        resolve(outDir, 'index.html'),
        dashboardIndex(template, { base: './' }),
      );
    },
    () => 'read-only UI with relative assets',
  );

  await step(
    'Eval catalog',
    async () => {
      await write('catalog.json', { evals: registry.catalog() });
      await write('evals.json', { evals: registry.metadata() });
      await write('suites.json', { suites: registry.suiteMetadata() });
      return { evals: registry.evals.length, suites: registry.suites.length };
    },
    ({ evals, suites }) =>
      `${count(evals, 'eval')} · ${count(suites, 'suite')}`,
  );

  const reports = createDashboardReportReader(reportRoot, registry);
  const snapshot = await step(
    'Run reports',
    async (progress) => {
      const all = await reports.listRuns();
      const runs = all.filter((run) => !run.archived);
      await write('runs.json', { runs });
      let trials = 0;
      let files = 0;
      const trialIds: string[] = [];
      for (const [index, run] of runs.entries()) {
        progress(`run ${index + 1}/${runs.length} · ${run.id.slice(0, 8)}`);
        const written = await snapshotRun(
          reports,
          run.id,
          directorySink(resolve(data, 'runs', run.id)),
        );
        trials += written.trialIds.length;
        files += written.files;
        trialIds.push(...written.trialIds);
      }
      return {
        runs: runs.length,
        trials,
        files,
        skipped: reports.legacyRunIds().length,
        archived: all.length - runs.length,
        runIds: runs.map((run) => run.id),
        trialIds,
      };
    },
    ({ runs, trials, files, skipped, archived }) =>
      `${count(runs, 'run')} · ${count(trials, 'trial')} · ${count(files, 'candidate file')}` +
      (archived ? ` · ${archived} archived excluded` : '') +
      (skipped ? ` · ${skipped} older-format skipped` : ''),
  );
  await step(
    'Route pages',
    async () => {
      const routes = staticRoutes({
        suites: registry.suites.map(authoringId),
        evals: registry.catalog().map((entry) => entry.path),
        runs: snapshot.runIds,
        trials: snapshot.trialIds,
      });
      for (const route of routes) {
        const file = resolve(outDir, `${route}.html`);
        await mkdir(dirname(file), { recursive: true });
        await writeFile(
          file,
          dashboardIndex(template, { base: baseFor(route) }),
        );
      }
      // Hosts that serve 404.html for unknown paths get a working root-mounted app.
      await writeFile(
        resolve(outDir, '404.html'),
        dashboardIndex(template, { base: '/' }),
      );
      return routes.length;
    },
    (pages) => `${count(pages, 'page')} with clean /path URLs`,
  );
  const { runIds: _runs, trialIds: _trials, ...summary } = snapshot;
  return { outDir, ...summary };
}

/**
 * Every dashboard URL known at build time, as file paths without `.html`.
 * Static hosts serve `/runs/abc` from `runs/abc.html`, so links and reloads
 * work without SPA rewrite rules. IDs that cannot be a safe file name are
 * skipped; those pages still open by navigating inside the app.
 */
export function staticRoutes(ids: {
  suites: readonly string[];
  evals: readonly string[];
  runs: readonly string[];
  trials: readonly string[];
}): string[] {
  const safe = (id: string) =>
    id.length > 0 && !/[/\\\0]/.test(id) && id !== '.' && id !== '..';
  const under = (prefix: string, values: readonly string[]) =>
    values.filter(safe).map((id) => `${prefix}/${id}`);
  return [
    'suites',
    'agents',
    'datasets',
    'invocations',
    'runs',
    ...under('suites', ids.suites),
    ...under('evals', ids.evals),
    ...under('runs', ids.runs),
    ...under('trials', ids.trials),
    ...under('workspaces', ids.trials),
  ];
}

/** `runs/abc.html` is served at `<mount>/runs/abc`; its base is one level up. */
function baseFor(route: string): string {
  const depth = route.split('/').length - 1;
  return depth ? '../'.repeat(depth) : './';
}

function count(value: number, noun: string): string {
  return `${value} ${noun}${value === 1 ? '' : 's'}`;
}

/** Receives one run's snapshot files, at paths relative to the run. */
export type SnapshotSink = {
  json(path: string, value: unknown): Promise<void>;
  bytes(path: string, data: Uint8Array): Promise<void>;
};

/** Writes a run's snapshot below `root` (static builds). */
export function directorySink(root: string): SnapshotSink {
  const target = (path: string) => {
    const file = resolve(root, path);
    if (!file.startsWith(`${resolve(root)}${sep}`))
      throw new Error(`Invalid snapshot path: ${path}`);
    return file;
  };
  return {
    async json(path, value) {
      const file = target(path);
      await mkdir(dirname(file), { recursive: true });
      await writeFile(file, `${JSON.stringify(value)}\n`);
    },
    async bytes(path, data) {
      const file = target(path);
      await mkdir(dirname(file), { recursive: true });
      await writeFile(file, data);
    },
  };
}

/**
 * One run's snapshot, shared by `evalkit build` (files on disk) and
 * `evalkit share` (an upload bundle): `trials.json`, then per trial
 * `detail.json`, `events.json`, `artifacts.json`, `workspace.json`, and the
 * candidate files under `workspace/`. Evaluator workspaces are never read.
 */
export async function snapshotRun(
  reports: ReturnType<typeof createDashboardReportReader>,
  runId: string,
  sink: SnapshotSink,
  options: { workspaceFiles?: boolean } = {},
): Promise<{ trialIds: string[]; files: number }> {
  const trials = await reports.listTrials(runId);
  await sink.json('trials.json', { trials });
  let files = 0;
  for (const trial of trials) {
    const base = `trials/${trial.id}`;
    await sink.json(
      `${base}/detail.json`,
      await reports.trialDetail(runId, trial.id),
    );
    await sink.json(`${base}/events.json`, {
      events: await reports.trajectory(runId, trial.id),
    });
    await sink.json(`${base}/artifacts.json`, {
      artifacts: await reports.listArtifacts(runId, trial.id),
    });
    const workspace = await reports.listCandidateWorkspace(runId, trial.id);
    await sink.json(`${base}/workspace.json`, workspace);
    if (options.workspaceFiles === false) continue;
    for (const entry of workspace) {
      if (entry.kind !== 'file') continue;
      const response = await reports.candidateFile(runId, trial.id, entry.path);
      await sink.bytes(
        `${base}/workspace/${entry.path}`,
        new Uint8Array(await response.arrayBuffer()),
      );
      files += 1;
    }
  }
  return { trialIds: trials.map((trial) => trial.id), files };
}

/** Total size and file count of a directory, for the build summary. */
export async function directorySize(
  root: string,
): Promise<{ bytes: number; files: number }> {
  let bytes = 0;
  let files = 0;
  for (const entry of await readdir(root, {
    withFileTypes: true,
    recursive: true,
  })) {
    if (!entry.isFile()) continue;
    bytes += (await stat(resolve(entry.parentPath, entry.name))).size;
    files += 1;
  }
  return { bytes, files };
}

async function prepareOutDir(outDir: string): Promise<void> {
  let entries: string[];
  try {
    if (!(await stat(outDir)).isDirectory())
      throw new Error(`Output path is not a directory: ${outDir}`);
    entries = await readdir(outDir);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
    await mkdir(outDir, { recursive: true });
    return;
  }
  if (!entries.length) return;
  // Never delete a directory EvalKit did not create.
  if (!entries.includes(MARKER))
    throw new Error(
      `Refusing to overwrite ${outDir}: it is not empty and was not created by evalkit build`,
    );
  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });
}
